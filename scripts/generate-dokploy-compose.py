"""Generate the single Compose file Dokploy reads before injecting domains.

Requires PyYAML==6.0.3. Run with --check in CI to prevent configuration drift.
"""
import copy
from pathlib import Path
import sys

import yaml

root = Path(__file__).resolve().parent.parent
config = copy.deepcopy(yaml.safe_load((root / "docker-compose.yml").read_text()))
for name, service in config["services"].items():
    service.pop("ports", None)
    service.pop("links", None)
    # Preserve internal names if Dokploy renames services; Traefik is attached
    # to web by Dokploy while all backend traffic stays on the wand network.
    service["networks"] = {"wand": {"aliases": [name]}}
for name, target, variable in (("db", "/var/lib/postgresql/data", "POSTGRES_DATA_PATH"), ("redis", "/data", "REDIS_DATA_PATH")):
    volumes = config["services"][name]["volumes"]
    for index, volume in enumerate(volumes):
        if isinstance(volume, str) and volume.split(":")[1] == target:
            volumes[index] = {
                "type": "bind",
                "source": "${" + variable + ":?Set the existing persistent data directory outside the Git checkout}",
                "target": target,
                "bind": {"create_host_path": False},
            }
content = "# Generated by scripts/generate-dokploy-compose.py; edit docker-compose.yml instead.\n"
content += "# Dokploy: enable Git submodules, configure existing data paths, route domains to web:80.\n"
content += yaml.safe_dump(config, sort_keys=False, width=120)
destination = root / "docker-compose.dokploy.yml"
if "--check" in sys.argv:
    if not destination.exists() or destination.read_text() != content:
        sys.exit("docker-compose.dokploy.yml is stale; run scripts/generate-dokploy-compose.py")
else:
    destination.write_text(content, encoding="utf-8", newline="\n")
